#!/usr/bin/env python3
"""Run the development-only query coverage/retrieval smoke benchmark; no labels from GT."""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from vehicle_gpt.api.app import _claim_answer
from vehicle_gpt.engines.common import DB_PATH
from vehicle_gpt.evaluation.baselines.direct_sql import DirectSqlBaseline
from vehicle_gpt.evaluation.baselines.rag import LexicalRagBaseline
from vehicle_gpt.evaluation.metrics import classification_metrics, latency_metrics
from vehicle_gpt.planner.inference import CaseStudyDemoPlanner
from vehicle_gpt.planner.router import DeterministicRouter

CASES = [
    (
        "range trend",
        "Why has driving range reduced over the last two weeks?",
        "ved:455",
        "trends",
        "insufficient",
        "E0",
    ),
    (
        "fuel efficiency trend",
        "When did fuel efficiency show its largest drop?",
        "ved:119",
        "unsupported",
        "unavailable",
        "E0",
    ),
    (
        "ADAS yesterday",
        "Show all ADAS disengagement events from yesterday.",
        "openlka:clip:716581635d83a1fa",
        "events",
        "insufficient",
        "E0",
    ),
    (
        "overheating precursor",
        "What happened in the 60 seconds before the battery overheating warning in the BMW i3?",
        "tum_bmw_i3:bmw_i3",
        "precursors",
        "partial",
        "E1",
    ),
    (
        "city/highway comparison",
        "Compare energy consumption between city and highway driving.",
        "ved:455",
        "unsupported",
        "unavailable",
        "E0",
    ),
]


def main():
    planner = CaseStudyDemoPlanner()
    router = DeterministicRouter()
    trace_rows = []
    expected_engine = []
    actual_engine = []
    expected_cov = []
    actual_cov = []
    expected_grade = []
    actual_grade = []
    latencies = []
    for label, question, vehicle_id, engine, cov, grade in CASES:
        plan = planner.plan(question, selected_vehicle_id=vehicle_id)
        result = router.execute(plan)
        answer = _claim_answer(plan, result)
        trace_rows.append(
            {
                "case": label,
                "intent": plan.intent.value,
                "plan_valid": True,
                "engine": result.engine,
                "question": question,
                "vehicle_id": vehicle_id,
                "selected_engine": plan.engine.value,
                "coverage": result.coverage.status,
                "grade": answer.overall_grade,
                "grounded": answer.grounded,
                "latency_ms": result.execution_ms,
                "answer": answer.text,
                "limitations": result.limitations,
                "evidence_count": len(answer.evidence),
                "provenance": result.provenance,
                "trip_ids": result.trip_ids,
            }
        )
        expected_engine.append(engine)
        actual_engine.append(plan.engine.value)
        expected_cov.append(cov)
        actual_cov.append(result.coverage.status)
        expected_grade.append(grade)
        actual_grade.append(answer.overall_grade)
        latencies.append(result.execution_ms)
    # SQL executor safety/performance smoke only. SQL is hand-authored, not generated by an SLM.
    sql = DirectSqlBaseline(DB_PATH).execute(
        "SELECT COUNT(*) AS vehicle_count FROM vehicle_registry"
    )
    # Lexical FTS5 retrieval is measured separately from any SLM answer generation.
    rag = LexicalRagBaseline(DB_PATH)
    rag_rows = []
    for label, question, *_ in CASES:
        retrieved = rag.retrieve(question, 5)
        rag_rows.append(
            {
                "case": label,
                "top_docs": [r["doc_id"] for r in retrieved],
                "top_k": len(retrieved),
            }
        )
    rag.close()
    q4 = next(r for r in trace_rows if r["case"] == "overheating precursor")
    if "TripB14" in q4["trip_ids"]:
        raise RuntimeError("held-out thermal trip leaked into development benchmark")
    if any("TripB14" in " ".join(r["top_docs"]) for r in rag_rows):
        raise RuntimeError("held-out trip leaked into lexical retrieval")
    report = {
        "created_utc": datetime.now(UTC).isoformat(),
        "scope": "development smoke only; no ground-truth DB opened; held-out split excluded from TRACE and lexical event index",
        "slm": {
            "status": "NOT MEASURED IN THIS FIXTURE BENCHMARK",
            "reason": "This benchmark is intentionally deterministic and does not call the SLM. Model/runtime details and real-inference results are recorded separately.",
        },
        "trace": {
            "status": "COMPLETE WITH LIMITATIONS",
            "cases": trace_rows,
            "intent_metrics": classification_metrics(expected_engine, actual_engine),
            "coverage_awareness_metrics": classification_metrics(
                expected_cov, actual_cov
            ),
            "grade_metrics": classification_metrics(expected_grade, actual_grade),
            "latency": latency_metrics(latencies),
        },
        "direct_sql": {
            "status": "SAFETY SMOKE ONLY; SLM GENERATION BLOCKED",
            "manual_select_result": sql,
        },
        "lexical_rag": {
            "status": "RETRIEVAL EXECUTED; SLM GENERATION BLOCKED",
            "retrieval_method": "SQLite FTS5/BM25 lexical retrieval",
            "cases": rag_rows,
        },
        "not_measured": [
            "SLM intent/plan validity",
            "token use",
            "GPU/VRAM",
            "end-to-end model latency",
            "held-out detection precision/recall",
            "causal accuracy",
        ],
    }
    out = ROOT / "artifacts/benchmark/dev_benchmark.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2) + "\n")
    print(
        json.dumps(
            {
                "output": str(out.relative_to(ROOT)),
                "trace_status": report["trace"]["status"],
                "intent_accuracy": report["trace"]["intent_metrics"]["accuracy"],
                "coverage_accuracy": report["trace"]["coverage_awareness_metrics"][
                    "accuracy"
                ],
                "grade_accuracy": report["trace"]["grade_metrics"]["accuracy"],
                "grounded": all(r["grounded"] for r in trace_rows),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
